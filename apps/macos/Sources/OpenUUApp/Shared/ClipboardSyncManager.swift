import AppKit
import CryptoKit
import Foundation
import ImageIO

/// Bidirectional macOS clipboard synchronizer (UTF-8 text + PNG/JPEG images + regular files) with:
/// - Bounded multi-hash history (`recentHashes`) to prevent A/B and multi-host relay ping-pong loops,
/// - Content-based SHA-256 file hashing (immune to timestamped cache filenames like Clipbara's `mac_<ms>.png`),
/// - Canonical decoded pixel fingerprinting (`64×64` 5-bit sRGB + dimensions) so PNG <-> TIFF <-> Bitmap <-> `.png` file
///   rewrites by third-party clipboard managers (Clipbara, Maccy, Paste, Raycast, uTools, Snipaste) never echo back.
@MainActor
final class ClipboardSyncManager {
    var isEnabled: Bool = true
    var onSendText: ((_ hash: String, _ text: String) -> Void)?
    var onSendImage: ((_ hash: String, _ mimeType: String, _ data: Data) -> Void)?
    var onSendFiles: ((_ urls: [URL]) -> Void)?
    var onStatusLog: ((String) -> Void)?

    private var pollTimer: Timer?
    private var isRunning = false
    private var lastObservedChangeCount: Int = NSPasteboard.general.changeCount
    private var recentHashes: [String] = []
    private var recentHashSet: Set<String> = []
    private var postApplyCooldownUntil: CFAbsoluteTime = 0
    private var lastAppliedWasImage: Bool = false

    private static let maxRecentHashes = 64
    private static let concealedTypes: Set<String> = [
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
    ]
    private static let imageExtensions: Set<String> = [
        "png", "jpg", "jpeg", "tiff", "tif", "webp", "heic", "bmp", "gif",
    ]
    private static let maxTextBytes = 2 * 1024 * 1024     // 2 MiB
    private static let maxImageBytes = 12 * 1024 * 1024   // 12 MiB
    private static let pngToJpegThreshold = 5 * 1024 * 1024

    func start() {
        guard !isRunning else { return }
        isRunning = true
        lastObservedChangeCount = NSPasteboard.general.changeCount
        pollTimer?.invalidate()
        pollTimer = Timer.scheduledTimer(withTimeInterval: 0.3, repeats: true) { [weak self] _ in
            Task { @MainActor [weak self] in
                self?.checkLocalPasteboardIfChanged()
            }
        }
    }

    func stop() {
        isRunning = false
        pollTimer?.invalidate()
        pollTimer = nil
        recentHashes.removeAll()
        recentHashSet.removeAll()
        postApplyCooldownUntil = 0
        lastAppliedWasImage = false
    }

    /// Call immediately before sending Cmd+V to ensure a fresh local copy (<300ms old) is synced first.
    func syncNowIfChanged() {
        guard isRunning, isEnabled else { return }
        checkLocalPasteboardIfChanged()
    }

    /// Call after an internal pasteboard write (e.g., dropped file injection) so we don't echo it back to peer.
    func ignoreCurrentPasteboardChange(forFiles urls: [URL] = []) {
        lastObservedChangeCount = NSPasteboard.general.changeCount
        if !urls.isEmpty {
            var hashes = [computeFileListContentHash(urls)]
            if urls.count == 1, Self.isImageFile(urls[0]),
               let px = computeCanonicalImagePixelHash(fileURL: urls[0]) {
                hashes.append(px)
            }
            recordSeen(hashes)
            postApplyCooldownUntil = CFAbsoluteTimeGetCurrent() + 1.0
            lastAppliedWasImage = urls.count == 1 && Self.isImageFile(urls[0])
        }
    }

    func applyRemoteClipboardFiles(_ urls: [URL]) {
        guard isEnabled, !urls.isEmpty else { return }
        let existing = urls.filter { FileManager.default.fileExists(atPath: $0.path) }
        guard !existing.isEmpty else { return }

        var hashes: [String] = [computeFileListContentHash(existing)]
        let singleImage = existing.count == 1 && Self.isImageFile(existing[0])
        if singleImage {
            if let pxHash = computeCanonicalImagePixelHash(fileURL: existing[0]) {
                hashes.append(pxHash)
            }
            if let rawData = try? Data(contentsOf: existing[0]), !rawData.isEmpty, rawData.count <= Self.maxImageBytes {
                hashes.append(sha256Hex(prefix: "image:", data: rawData))
            }
        }

        // Crucial loop guard: if we already sent or applied this exact file content or image pixels,
        // NEVER rewrite NSPasteboard.general (otherwise local clipboard history apps will clone it endlessly!).
        if hasSeenAny(hashes) {
            cleanupTempInboxFilesIfNeeded(existing)
            return
        }
        recordSeen(hashes)

        let pb = NSPasteboard.general
        pb.clearContents()
        pb.writeObjects(existing as [NSURL])
        lastObservedChangeCount = pb.changeCount
        postApplyCooldownUntil = CFAbsoluteTimeGetCurrent() + 1.0
        lastAppliedWasImage = singleImage

        let names = existing.map(\.lastPathComponent).joined(separator: ", ")
        onStatusLog?("已同步对端文件到剪贴板，可直接 ⌘V 粘贴: \(names)")
    }

    func applyRemoteClipboard(hash: String, clipKind: Int32, text: String?, mimeType: String?, imageBase64: String?) {
        guard isEnabled, !hash.isEmpty else { return }
        if hasSeenAny([hash]) {
            return
        }

        let pb = NSPasteboard.general
        switch clipKind {
        case 0: // TEXT
            guard let text, !text.isEmpty else { return }
            let localTextHash = sha256Hex(prefix: "text:", data: Data(text.utf8))
            if hasSeenAny([hash, localTextHash]) {
                return
            }
            recordSeen([hash, localTextHash])

            pb.clearContents()
            pb.setString(text, forType: .string)
            lastObservedChangeCount = pb.changeCount
            postApplyCooldownUntil = CFAbsoluteTimeGetCurrent() + 0.8
            lastAppliedWasImage = false
            onStatusLog?("已同步对端文本剪贴板 (\(text.count) 字)")

        case 1: // IMAGE
            guard let b64 = imageBase64, !b64.isEmpty,
                  let data = Data(base64Encoded: b64), !data.isEmpty else {
                return
            }
            var hashes = [hash, sha256Hex(prefix: "image:", data: data)]
            if let pxHash = computeCanonicalImagePixelHash(data: data) {
                hashes.append(pxHash)
            }
            if hasSeenAny(hashes) {
                return
            }
            recordSeen(hashes)

            pb.clearContents()
            let mime = (mimeType ?? "image/png").lowercased()
            if mime == "image/jpeg" || mime == "image/jpg" {
                pb.setData(data, forType: NSPasteboard.PasteboardType("public.jpeg"))
                if let img = NSImage(data: data), let tiff = img.tiffRepresentation {
                    pb.setData(tiff, forType: .tiff)
                }
            } else {
                pb.setData(data, forType: .png)
            }
            lastObservedChangeCount = pb.changeCount
            postApplyCooldownUntil = CFAbsoluteTimeGetCurrent() + 1.0
            lastAppliedWasImage = true
            let kb = max(1, data.count / 1024)
            onStatusLog?("已同步对端图片剪贴板 (\(kb) KB)")

        default:
            break
        }
    }

    private func checkLocalPasteboardIfChanged() {
        guard isRunning, isEnabled else { return }
        let pb = NSPasteboard.general
        let currentCount = pb.changeCount
        guard currentCount != lastObservedChangeCount else { return }
        lastObservedChangeCount = currentCount

        let rawTypes = Set((pb.types ?? []).map(\.rawValue))
        // Never sync concealed/transient items from password managers (1Password, Keychain, etc.).
        if !rawTypes.isDisjoint(with: Self.concealedTypes) {
            return
        }

        let inPostApplyWindow = CFAbsoluteTimeGetCurrent() < postApplyCooldownUntil

        // Handle file URLs on pasteboard (Finder file copy OR clipboard-history manager materialized image file).
        if rawTypes.contains(NSPasteboard.PasteboardType.fileURL.rawValue) {
            if let urls = pb.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [URL] {
                let fm = FileManager.default
                let maxFileBytes: Int64 = 512 * 1024 * 1024
                let regularFiles = urls.filter { url in
                    var isDir: ObjCBool = false
                    guard fm.fileExists(atPath: url.path, isDirectory: &isDir), !isDir.boolValue else { return false }
                    let size = (try? fm.attributesOfItem(atPath: url.path)[.size] as? Int64) ?? 0
                    return size > 0 && size <= maxFileBytes
                }
                guard !regularFiles.isEmpty else { return }

                let contentHash = computeFileListContentHash(regularFiles)
                var candidateHashes = [contentHash]
                let isSingleImageFile = regularFiles.count == 1 && Self.isImageFile(regularFiles[0])
                var singleImagePixelHash: String?
                if isSingleImageFile {
                    if let pxHash = computeCanonicalImagePixelHash(fileURL: regularFiles[0]) {
                        singleImagePixelHash = pxHash
                        candidateHashes.append(pxHash)
                    }
                    if let rawData = try? Data(contentsOf: regularFiles[0]), !rawData.isEmpty, rawData.count <= Self.maxImageBytes {
                        candidateHashes.append(sha256Hex(prefix: "image:", data: rawData))
                    }
                }

                // If any content or pixel fingerprint matches a recently sent/applied item, absorb silently!
                if hasSeenAny(candidateHashes) {
                    recordSeen(candidateHashes)
                    return
                }

                // Extra guard: if a clipboard manager rewrote an image into a temp `.png` within 1s of us applying an image,
                // absorb it instead of echoing.
                if inPostApplyWindow && lastAppliedWasImage && isSingleImageFile && Self.looksLikeClipboardManagerCacheFile(regularFiles[0]) {
                    recordSeen(candidateHashes)
                    return
                }

                // If a clipboard manager (e.g. Clipbara) materialized a user screenshot/image copy into `mac_<ms>.png`
                // (no Finder node ref, cache/timestamp path, and image bytes present), sync it cleanly as an IMAGE
                // rather than a temp-named file attachment!
                let isFinderFileCopy = rawTypes.contains("com.apple.finder.noderef")
                if isSingleImageFile && !isFinderFileCopy && Self.looksLikeClipboardManagerCacheFile(regularFiles[0]),
                   let imagePayload = extractImageFromPasteboard(pb) ?? loadImageFileIfSupported(regularFiles[0]) {
                    let imgDataHash = sha256Hex(prefix: "image:", data: imagePayload.data)
                    candidateHashes.append(imgDataHash)
                    if let px = singleImagePixelHash ?? computeCanonicalImagePixelHash(data: imagePayload.data) {
                        candidateHashes.append(px)
                    }
                    if hasSeenAny(candidateHashes) {
                        recordSeen(candidateHashes)
                        return
                    }
                    recordSeen(candidateHashes)
                    onSendImage?(imgDataHash, imagePayload.mimeType, imagePayload.data)
                    return
                }

                recordSeen(candidateHashes)
                onSendFiles?(regularFiles)
            }
            return
        }

        // Priority 1: Image on pasteboard (screenshots, WeChat "Copy Image", browser "Copy Image")
        if let imagePayload = extractImageFromPasteboard(pb) {
            emitImageIfNew(mimeType: imagePayload.mimeType, data: imagePayload.data)
            return
        }

        // Priority 2: Plain UTF-8 text
        if let text = pb.string(forType: .string), !text.isEmpty {
            let utf8 = Data(text.utf8)
            guard utf8.count <= Self.maxTextBytes else { return }
            let hash = sha256Hex(prefix: "text:", data: utf8)
            guard !hasSeenAny([hash]) else { return }
            recordSeen([hash])
            onSendText?(hash, text)
        }
    }

    private func emitImageIfNew(mimeType: String, data: Data) {
        guard !data.isEmpty, data.count <= Self.maxImageBytes else { return }
        let dataHash = sha256Hex(prefix: "image:", data: data)
        var hashes = [dataHash]
        if let pxHash = computeCanonicalImagePixelHash(data: data) {
            hashes.append(pxHash)
        }
        guard !hasSeenAny(hashes) else {
            recordSeen(hashes)
            return
        }
        recordSeen(hashes)
        onSendImage?(dataHash, mimeType, data)
    }

    // MARK: - Ring-Buffer Hash Deduplication & Fingerprinting

    private func hasSeenAny(_ hashes: [String]) -> Bool {
        for h in hashes where !h.isEmpty {
            if recentHashSet.contains(h) {
                return true
            }
        }
        return false
    }

    private func recordSeen(_ hashes: [String]) {
        for h in hashes where !h.isEmpty {
            if recentHashSet.insert(h).inserted {
                recentHashes.append(h)
                if recentHashes.count > Self.maxRecentHashes {
                    let evicted = recentHashes.removeFirst()
                    recentHashSet.remove(evicted)
                }
            }
        }
    }

    private static func isImageFile(_ url: URL) -> Bool {
        imageExtensions.contains(url.pathExtension.lowercased())
    }

    private static func looksLikeClipboardManagerCacheFile(_ url: URL) -> Bool {
        let path = url.path.lowercased()
        if path.contains("/clipbara") || path.contains("/maccy") || path.contains("/ecopaste") ||
           path.contains("/paste/") || path.contains("/cleanclip") || path.contains("/utools") ||
           path.contains("/raycast") || path.contains("/openuu-inbox/") {
            return true
        }
        let name = url.deletingPathExtension().lastPathComponent
        if name.hasPrefix("mac_"), name.dropFirst(4).allSatisfy(\.isNumber), name.count >= 14 {
            return true
        }
        return false
    }

    private func cleanupTempInboxFilesIfNeeded(_ urls: [URL]) {
        let fm = FileManager.default
        for url in urls where url.path.contains("/openuu-inbox/") {
            try? fm.removeItem(at: url.deletingLastPathComponent())
        }
    }

    /// Computes a deterministic pixel hash (`64×64` 5-bit sRGB RGBA + original pixel dimensions) so the exact same
    /// image re-encoded across PNG, TIFF, Windows GDI+ Bitmap, JPEG, or `mac_<ms>.png` files always matches!
    private func computeCanonicalImagePixelHash(data: Data) -> String? {
        guard let src = CGImageSourceCreateWithData(data as CFData, nil),
              let cgImage = CGImageSourceCreateImageAtIndex(src, 0, nil) else {
            return nil
        }
        return computeCanonicalImagePixelHash(cgImage: cgImage)
    }

    private func computeCanonicalImagePixelHash(fileURL: URL) -> String? {
        guard let src = CGImageSourceCreateWithURL(fileURL as CFURL, nil),
              let cgImage = CGImageSourceCreateImageAtIndex(src, 0, nil) else {
            return nil
        }
        return computeCanonicalImagePixelHash(cgImage: cgImage)
    }

    private func computeCanonicalImagePixelHash(cgImage: CGImage) -> String? {
        let origW = cgImage.width
        let origH = cgImage.height
        guard origW > 0, origH > 0 else { return nil }

        let side = 64
        let bytesPerRow = side * 4
        var pixels = [UInt8](repeating: 0, count: side * bytesPerRow)
        let colorSpace = CGColorSpace(name: CGColorSpace.sRGB) ?? CGColorSpaceCreateDeviceRGB()
        let bitmapInfo = CGImageAlphaInfo.premultipliedLast.rawValue | CGBitmapInfo.byteOrder32Big.rawValue

        let ok = pixels.withUnsafeMutableBytes { rawBuf -> Bool in
            guard let base = rawBuf.baseAddress,
                  let ctx = CGContext(
                      data: base,
                      width: side,
                      height: side,
                      bitsPerComponent: 8,
                      bytesPerRow: bytesPerRow,
                      space: colorSpace,
                      bitmapInfo: bitmapInfo
                  ) else {
                return false
            }
            ctx.interpolationQuality = .medium
            ctx.draw(cgImage, in: CGRect(x: 0, y: 0, width: side, height: side))
            return true
        }
        guard ok else { return nil }

        // Mask top 5 bits (`0xF8`) per channel so ±7/255 ColorSync / GDI+ / JPEG rounding produces identical digests.
        for i in pixels.indices {
            pixels[i] &= 0xF8
        }

        var hasher = SHA256()
        hasher.update(data: Data("img-px:\(origW)x\(origH):".utf8))
        hasher.update(data: Data(pixels))
        let digest = hasher.finalize()
        return digest.map { String(format: "%02x", $0) }.joined()
    }

    /// Hashes actual file byte content (head 1 MiB + tail 1 MiB + byte length) instead of filename,
    /// defeating timestamped filenames (`mac_1795496970172.png` -> `mac_1795496973909.png`).
    private func computeFileListContentHash(_ urls: [URL]) -> String {
        let perFile = urls.map { computeSingleFileContentHash($0) }.sorted().joined(separator: "|")
        return sha256Hex(prefix: "files-content:", data: Data(perFile.utf8))
    }

    private func computeSingleFileContentHash(_ url: URL) -> String {
        let size = (try? FileManager.default.attributesOfItem(atPath: url.path)[.size] as? UInt64) ?? 0
        guard size > 0, let fh = try? FileHandle(forReadingFrom: url) else {
            return "\(url.lastPathComponent):\(size)"
        }
        defer { try? fh.close() }

        let sampleChunk = 1024 * 1024 // 1 MiB
        var hasher = SHA256()
        hasher.update(data: Data("sz=\(size):".utf8))
        if let head = try? fh.read(upToCount: sampleChunk) {
            hasher.update(data: head)
        }
        if size > UInt64(sampleChunk) {
            let tailOffset = size > UInt64(sampleChunk * 2) ? (size - UInt64(sampleChunk)) : UInt64(sampleChunk)
            if (try? fh.seek(toOffset: tailOffset)) != nil,
               let tail = try? fh.read(upToCount: sampleChunk) {
                hasher.update(data: tail)
            }
        }
        return hasher.finalize().map { String(format: "%02x", $0) }.joined()
    }

    // MARK: - Image Extraction & Compression

    private func extractImageFromPasteboard(_ pb: NSPasteboard) -> (mimeType: String, data: Data)? {
        if let png = pb.data(forType: .png), !png.isEmpty {
            return compressIfNeeded(pngData: png)
        }
        let jpegType = NSPasteboard.PasteboardType("public.jpeg")
        if let jpg = pb.data(forType: jpegType), !jpg.isEmpty, jpg.count <= Self.maxImageBytes {
            return ("image/jpeg", jpg)
        }
        if let tiff = pb.data(forType: .tiff), !tiff.isEmpty,
           let rep = NSBitmapImageRep(data: tiff) {
            if let png = rep.representation(using: .png, properties: [:]) {
                return compressIfNeeded(pngData: png, existingRep: rep)
            }
        }
        return nil
    }

    private func compressIfNeeded(pngData: Data, existingRep: NSBitmapImageRep? = nil) -> (mimeType: String, data: Data)? {
        if pngData.count <= Self.pngToJpegThreshold {
            return ("image/png", pngData)
        }
        if let rep = existingRep ?? NSBitmapImageRep(data: pngData),
           let jpg = rep.representation(using: .jpeg, properties: [.compressionFactor: 0.88]),
           jpg.count <= Self.maxImageBytes {
            return ("image/jpeg", jpg)
        }
        return pngData.count <= Self.maxImageBytes ? ("image/png", pngData) : nil
    }

    private func loadImageFileIfSupported(_ url: URL) -> (mimeType: String, data: Data)? {
        let ext = url.pathExtension.lowercased()
        guard Self.imageExtensions.contains(ext) else { return nil }
        guard let attrs = try? FileManager.default.attributesOfItem(atPath: url.path),
              let size = attrs[.size] as? Int, size > 0, size <= Self.maxImageBytes else {
            return nil
        }
        if ext == "png", let data = try? Data(contentsOf: url) {
            return compressIfNeeded(pngData: data)
        }
        if (ext == "jpg" || ext == "jpeg"), let data = try? Data(contentsOf: url) {
            return ("image/jpeg", data)
        }
        if let img = NSImage(contentsOf: url),
           let tiff = img.tiffRepresentation,
           let rep = NSBitmapImageRep(data: tiff),
           let png = rep.representation(using: .png, properties: [:]) {
            return compressIfNeeded(pngData: png, existingRep: rep)
        }
        return nil
    }

    private func sha256Hex(prefix: String, data: Data) -> String {
        var hasher = SHA256()
        hasher.update(data: Data(prefix.utf8))
        hasher.update(data: data)
        let digest = hasher.finalize()
        return digest.map { String(format: "%02x", $0) }.joined()
    }
}
